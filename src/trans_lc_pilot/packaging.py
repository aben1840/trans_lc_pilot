"""Standalone CLI entry point for packaging the project as a plugin.

Usage::

    trans-lc-pilot-package [--out FILE]

Builds a wheel from the current source tree, then writes a
distributable zip archive whose contents let a customer install
dependencies and run the plugin without any extra tooling beyond
a stock Python 3.12+::

    setup.cmd             Windows installer: runs ``python -m pip``
                          to upgrade pip, install the locked runtime
                          requirements, install the project wheel
                          (``pip install --no-deps *.whl``), and
                          smoke-test the import.
    requirements.txt      Pip-compatible lockfile generated by
                          ``pip-compile pyproject.toml`` at dev time
                          and shipped verbatim, so the customer
                          machine does not need a lockfile tool
                          of its own.
    *.whl                 Pre-built wheel produced by
                          ``pip wheel .`` at packaging time. The
                          customer side never builds — it only
                          unpacks.

This entry point does **not** handle document-only operations
(``inspect``, ``preview``, ``split``, ``assemble``). Those live on
``trans-lc-pilot`` (see :mod:`trans_lc_pilot.cli`).
"""
from __future__ import annotations

import argparse
import shutil
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]
REQUIREMENTS_TXT = PROJECT_ROOT / "requirements.txt"
DIST_DIR = PROJECT_ROOT / "dist"
"""Where ``pip wheel`` writes its output; git-ignored."""

_SETUP_CMD_BODY = (
    "@echo off\r\n"
    "setlocal\r\n"
    "chcp 65001 >nul\r\n"
    "cd /d \"%~dp0\"\r\n"
    "\r\n"
    "echo === trans-lc-pilot setup ===\r\n"
    "\r\n"
    "where python >nul 2>&1\r\n"
    "if errorlevel 1 (\r\n"
    "    echo error: Python not found on PATH. Install Python 3.12+ and retry.\r\n"
    "    exit /b 1\r\n"
    ")\r\n"
    "\r\n"
    "for /f \"delims=\" %%v in ('python --version 2^>^&1') do set PYVER=%%v\r\n"
    "echo using %PYVER%\r\n"
    "\r\n"
    "python -m pip install --upgrade pip\r\n"
    "if errorlevel 1 exit /b 1\r\n"
    "\r\n"
    "python -m pip install --only-binary=:all: -r requirements.txt\r\n"
    "if errorlevel 1 (\r\n"
    "    echo error: dependency install failed. Check network / PyPI access.\r\n"
    "    exit /b 1\r\n"
    ")\r\n"
    "\r\n"
    "python -m pip install --no-deps trans_lc_pilot-0.1.0-py3-none-any.whl\r\n"
    "if errorlevel 1 exit /b 1\r\n"
    "\r\n"
    "python -c \"import trans_lc_pilot\" || (\r\n"
    "    echo error: trans_lc_pilot import failed after install\r\n"
    "    exit /b 1\r\n"
    ")\r\n"
    "\r\n"
    "echo.\r\n"
    "echo Setup complete.\r\n"
    "echo   trans-lc-pilot inspect FILE\r\n"
    "echo   trans-lc-pilot split FILE --level N\r\n"
    "echo   trans-lc-pilot assemble BUNDLE_DIR\r\n"
    "echo   trans-lc-pilot-agent \"prompt\"\r\n"
    "endlocal\r\n"
    "exit /b 0\r\n"
)
"""Windows installer payload; ``\\r\\n`` line endings keep the file
Windows-native, which a ``.cmd`` should be."""


def parse_args(argv: list[str]) -> argparse.Namespace:
    """Parse command-line arguments.

    Args:
        argv: Argument vector excluding the program name.

    Returns:
        argparse.Namespace: Parsed arguments. ``out`` names the zip
        archive to write.
    """
    parser = argparse.ArgumentParser(prog="trans-lc-pilot-package")
    parser.add_argument(
        "--out",
        metavar="FILE",
        default="plugin.zip",
        help="Path of the zip to write (default: ./plugin.zip).",
    )
    return parser.parse_args(argv)


def _build_wheel() -> Path:
    """Run ``pip wheel`` against the project and return the wheel path.

    Uses a private temporary directory to avoid mixing in stale
    wheels from previous runs, then copies the produced wheel into
    ``dist/`` so it is inspectable after packaging (and so the same
    path is reported if packaging is re-run).

    Returns:
        Path: Location of ``trans_lc_pilot-<version>-py3-none-any.whl``
        inside ``dist/``.

    Raises:
        RuntimeError: If ``pip wheel`` exits non-zero, or produces
            no wheel file.
        OSError: If the wheel cannot be copied into ``dist/``.
    """
    DIST_DIR.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as tmp:
        cmd = [
            sys.executable, "-m", "pip", "wheel", ".",
            "-w", tmp, "--no-deps", "--quiet",
        ]
        result = subprocess.run(
            cmd, cwd=PROJECT_ROOT, capture_output=True, text=True
        )
        if result.returncode != 0:
            raise RuntimeError(
                f"pip wheel failed (exit {result.returncode}): "
                f"{result.stderr.strip() or result.stdout.strip()}"
            )
        wheels = list(Path(tmp).glob("*.whl"))
        if not wheels:
            raise RuntimeError("pip wheel produced no .whl file")
        wheel = wheels[0]
        target = DIST_DIR / wheel.name
        shutil.copy(wheel, target)
        return target


def _write_plugin(out_path: Path) -> None:
    """Write the plugin archive at ``out_path``.

    First builds a wheel via :func:`_build_wheel`, then zips it with
    the installer script and the locked ``requirements.txt``. No
    source tree, no ``pyproject.toml``, no build artifacts beyond
    the single wheel — the customer side never builds.

    Args:
        out_path: Destination zip path.

    Raises:
        RuntimeError: If the wheel cannot be built.
        OSError: When any input file cannot be read or written.
    """
    wheel = _build_wheel()
    with zipfile.ZipFile(out_path, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("setup.cmd", _SETUP_CMD_BODY)
        zf.writestr("requirements.txt", REQUIREMENTS_TXT.read_bytes())
        zf.write(wheel, wheel.name)


def main(argv: list[str] | None = None) -> int:
    """Entry point for the ``trans-lc-pilot-package`` console script.

    Args:
        argv: Optional argument vector excluding the program name;
            defaults to ``sys.argv[1:]`` when ``None``.

    Returns:
        int: Exit code; ``0`` for a clean run, ``1`` on failure.
    """
    args = parse_args(list(argv if argv is not None else sys.argv[1:]))
    out_path = Path(args.out)
    try:
        _write_plugin(out_path)
    except (OSError, RuntimeError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    print(f"plugin: {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
