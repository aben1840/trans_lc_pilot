"""Standalone CLI entry point for packaging the project as a plugin.

Usage::

    trans-lc-pilot-package [--out FILE]

Produces a distributable zip archive whose contents let a customer
install dependencies and run the plugin without any extra tooling
beyond a stock Python 3.12+::

    setup.cmd             Windows installer: runs ``python -m pip``
                          to upgrade pip, install the locked runtime
                          requirements, install the project itself,
                          and smoke-test the import.
    requirements.txt      Pip-compatible lockfile generated by
                          ``pip-compile pyproject.toml`` at dev time
                          and shipped verbatim, so the customer
                          machine does not need a lockfile tool of
                          its own.
    pyproject.toml        Project metadata; ``pip install .`` reads
                          it to register the three console scripts.
    src/                  Source tree; ``pip install .`` places it
                          on ``sys.path``.

This entry point does **not** handle document-only operations
(``inspect``, ``preview``, ``split``, ``assemble``). Those live on
``trans-lc-pilot`` (see :mod:`trans_lc_pilot.cli`).
"""
from __future__ import annotations

import argparse
import sys
import zipfile
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[2]
REQUIREMENTS_TXT = PROJECT_ROOT / "requirements.txt"
PYPROJECT_TOML = PROJECT_ROOT / "pyproject.toml"
SRC_DIR = PROJECT_ROOT / "src"

_EXCLUDE_DIRS = {"__pycache__", ".ruff_cache", ".pytest_cache", ".venv"}
_EXCLUDE_SUFFIXES = {".pyc", ".pyo"}

_SETUP_CMD_BODY = (
    "@echo off\r\n"
    "setlocal\r\n"
    "chcp 65001 >nul\r\n"
    "cd /d \"%~dp0\"\r\n"
    "\r\n"
    "echo === trans-lc-pilot setup ===\r\n"
    "\r\n"
    "where python >nul 2>&1\r\n"
    "if errorlevel 1 (\r\n"
    "    echo error: Python not found on PATH. Install Python 3.12+ and retry.\r\n"
    "    exit /b 1\r\n"
    ")\r\n"
    "\r\n"
    "for /f \"delims=\" %%v in ('python --version 2^>^&1') do set PYVER=%%v\r\n"
    "echo using %PYVER%\r\n"
    "\r\n"
    "python -m pip install --upgrade pip\r\n"
    "if errorlevel 1 exit /b 1\r\n"
    "\r\n"
    "python -m pip install --only-binary=:all: -r requirements.txt\r\n"
    "if errorlevel 1 (\r\n"
    "    echo error: dependency install failed. Check network / PyPI access.\r\n"
    "    exit /b 1\r\n"
    ")\r\n"
    "\r\n"
    "python -m pip install --no-deps .\r\n"
    "if errorlevel 1 exit /b 1\r\n"
    "\r\n"
    "python -c \"import trans_lc_pilot\" || (\r\n"
    "    echo error: trans_lc_pilot import failed after install\r\n"
    "    exit /b 1\r\n"
    ")\r\n"
    "\r\n"
    "echo.\r\n"
    "echo Setup complete.\r\n"
    "echo   trans-lc-pilot inspect FILE\r\n"
    "echo   trans-lc-pilot split FILE --level N\r\n"
    "echo   trans-lc-pilot assemble BUNDLE_DIR\r\n"
    "echo   trans-lc-pilot-agent \"prompt\"\r\n"
    "endlocal\r\n"
    "exit /b 0\r\n"
)
"""Windows installer payload; ``\\r\\n`` line endings keep the file
Windows-native, which a ``.cmd`` should be."""


def parse_args(argv: list[str]) -> argparse.Namespace:
    """Parse command-line arguments.

    Args:
        argv: Argument vector excluding the program name.

    Returns:
        argparse.Namespace: Parsed arguments. ``out`` names the zip
        archive to write.
    """
    parser = argparse.ArgumentParser(prog="trans-lc-pilot-package")
    parser.add_argument(
        "--out",
        metavar="FILE",
        default="plugin.zip",
        help="Path of the zip to write (default: ./plugin.zip).",
    )
    return parser.parse_args(argv)


def _is_excluded(path: Path) -> bool:
    """Return whether ``path`` should be skipped when packing src/.

    Args:
        path: A file under src/ being considered for inclusion.

    Returns:
        bool: True when any parent directory is in the exclusion
            list or the file's suffix matches a Python bytecode
            suffix.
    """
    return (
        any(part in _EXCLUDE_DIRS for part in path.parts)
        or path.suffix in _EXCLUDE_SUFFIXES
    )


def _read_requirements() -> bytes:
    """Return the pip-compatible requirements text shipped with the repo.

    The file is generated by ``pip-compile pyproject.toml`` at dev time
    and committed alongside the source, so the customer machine does
    not need any lockfile tool of its own. Read as bytes to preserve
    the original line endings (pip-compile writes CRLF on Windows);
    universal-newline mode would silently strip the carriage returns
    and the file would no longer match the on-disk copy.

    Returns:
        bytes: Raw contents of ``requirements.txt`` at the project root.

    Raises:
        FileNotFoundError: When ``requirements.txt`` has not been
            generated yet — the developer ran
            ``trans-lc-pilot-package`` before bootstrap.
    """
    return REQUIREMENTS_TXT.read_bytes()


def _add_tree(zf: zipfile.ZipFile, root: Path, *, arcname_root: str) -> None:
    """Add every non-excluded file under ``root`` to the zip.

    Args:
        zf: Open zip to write into.
        root: Directory whose contents are packed.
        arcname_root: Top-level directory name used inside the zip
            (forward slashes; no trailing separator).
    """
    for path in sorted(root.rglob("*")):
        if not path.is_file() or _is_excluded(path):
            continue
        arcname = f"{arcname_root}/{path.relative_to(root).as_posix()}"
        zf.write(path, arcname)


def _write_plugin(out_path: Path) -> None:
    """Write the plugin archive at ``out_path``.

    The archive holds ``setup.cmd`` (Windows installer), the locked
    ``requirements.txt``, ``pyproject.toml`` (so ``pip install .``
    can register the three console scripts), and the full ``src/``
    tree. Nothing in ``.venv/``, ``__pycache__/``, or test/lint
    caches is shipped.

    Args:
        out_path: Destination zip path.

    Raises:
        OSError: When any input file cannot be read or written.
    """
    with zipfile.ZipFile(out_path, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("setup.cmd", _SETUP_CMD_BODY)
        zf.writestr("requirements.txt", _read_requirements())
        zf.write(PYPROJECT_TOML, "pyproject.toml")
        _add_tree(zf, SRC_DIR, arcname_root="src")


def main(argv: list[str] | None = None) -> int:
    """Entry point for the ``trans-lc-pilot-package`` console script.

    Args:
        argv: Optional argument vector excluding the program name;
            defaults to ``sys.argv[1:]`` when ``None``.

    Returns:
        int: Exit code; ``0`` for a clean run, ``1`` on failure.
    """
    args = parse_args(list(argv if argv is not None else sys.argv[1:]))
    out_path = Path(args.out)
    try:
        _write_plugin(out_path)
    except OSError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    print(f"plugin: {out_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
